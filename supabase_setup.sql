-- বন্ধুর বন্ধন সমিতি লিমিটেড: Flask app-এর জন্য Supabase PostgreSQL schema
-- আগের public.members / public.deposits টেবিল মুছে ফেলা হবে না।
-- এই অ্যাপ আলাদা app_users এবং member_deposits টেবিল ব্যবহার করে।

create table if not exists public.app_users (
    id bigint generated by default as identity primary key,
    username text not null unique,
    password_hash text not null,
    role text not null check (role in ('admin', 'member')),
    full_name text not null,
    father_name text not null default '',
    mother_name text not null default '',
    birth_date text not null default '',
    phone text not null default '',
    address text not null default '',
    nid text not null default '',
    joined_month text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.member_deposits (
    id bigint generated by default as identity primary key,
    member_id bigint not null references public.app_users(id) on delete cascade,
    month text not null,
    amount integer not null check (amount > 0),
    paid_at date not null,
    note text not null default '',
    created_by bigint references public.app_users(id)
);

create index if not exists idx_member_deposits_member_month
    on public.member_deposits(member_id, month);

